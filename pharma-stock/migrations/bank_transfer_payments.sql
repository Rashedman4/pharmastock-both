CREATE UNIQUE INDEX IF NOT EXISTS firm_profit_payments_manual_reference_uq
    ON firm_profit_payments (manual_reference)
    WHERE manual_reference IS NOT NULL;

CREATE INDEX IF NOT EXISTS firm_profit_payments_method_status_idx
    ON firm_profit_payments (payment_method, status, created_at DESC);

