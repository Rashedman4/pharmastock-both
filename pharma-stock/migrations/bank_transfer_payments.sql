-- ------------------------------------------------------------
-- Admin-managed payout destinations
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS firm_bank_accounts (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_name      character varying(150) NOT NULL,
    bank_name         character varying(150) NOT NULL,
    iban              character varying(50)  NOT NULL,
    swift_code        character varying(50),
    currency          character varying(3)   NOT NULL DEFAULT 'USD',
    country           character varying(80),
    instructions      text,
    is_active         boolean NOT NULL DEFAULT true,
    created_at        timestamp with time zone NOT NULL DEFAULT now(),
    updated_at        timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT firm_bank_accounts_currency_check
        CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE INDEX IF NOT EXISTS firm_bank_accounts_active_idx
    ON firm_bank_accounts (is_active, updated_at DESC);

-- ------------------------------------------------------------
-- Manual-transfer workflow columns on firm_profit_payments
-- ------------------------------------------------------------
ALTER TABLE firm_profit_payments
    ADD COLUMN IF NOT EXISTS payment_method      character varying(30) NOT NULL DEFAULT 'STRIPE',
    ADD COLUMN IF NOT EXISTS bank_account_id     integer,
    ADD COLUMN IF NOT EXISTS manual_reference    character varying(80),
    ADD COLUMN IF NOT EXISTS transfer_reference  character varying(120),
    ADD COLUMN IF NOT EXISTS proof_url           text,
    ADD COLUMN IF NOT EXISTS proof_name          character varying(255),
    ADD COLUMN IF NOT EXISTS submitted_at        timestamp with time zone,
    ADD COLUMN IF NOT EXISTS reviewed_by         integer,
    ADD COLUMN IF NOT EXISTS reviewed_at         timestamp with time zone,
    ADD COLUMN IF NOT EXISTS review_note         text;

-- Existing rows are all Stripe payments; the DEFAULT above already
-- backfills them to 'STRIPE', so no UPDATE is needed.

-- ------------------------------------------------------------
