-- ------------------------------------------------------------
-- Widen the status CHECK.
-- Production currently allows only:
--   PENDING, CHECKOUT_CREATED, PAID, FAILED, EXPIRED, CANCELLED
-- The manual-transfer flow adds four more states. Without this, the first
-- bank-transfer payment that leaves PENDING raises a check_violation.
-- ------------------------------------------------------------
ALTER TABLE firm_profit_payments
    DROP CONSTRAINT IF EXISTS firm_profit_payments_status_check;

ALTER TABLE firm_profit_payments
    ADD CONSTRAINT firm_profit_payments_status_check
    CHECK (status IN (
        'PENDING', 'CHECKOUT_CREATED', 'AWAITING_TRANSFER', 'PROOF_SUBMITTED',
        'UNDER_REVIEW', 'PAID', 'REJECTED', 'FAILED', 'EXPIRED', 'CANCELLED'
    ));

ALTER TABLE firm_profit_payments
    DROP CONSTRAINT IF EXISTS firm_profit_payments_method_check;

ALTER TABLE firm_profit_payments
    ADD CONSTRAINT firm_profit_payments_method_check
    CHECK (payment_method IN ('STRIPE', 'BANK_TRANSFER', 'CASH', 'OTHER'));

-- ------------------------------------------------------------
-- Indexes
